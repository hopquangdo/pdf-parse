"""Ports: what the application needs from the outside world. Implementations live in infrastructure/.

Services depend on these Protocols only, so a reader, a store or a template can be swapped (or faked in a test)
without touching the use case.
"""
from pathlib import Path
from typing import Any, ContextManager, Dict, List, Optional, Protocol, Sequence, Tuple

from src.domain.models import ExtractionJob


class VisionReader(Protocol):
    """Reads an image into row dicts (free-form page or region)."""
    def read(self, image_png: bytes, label: str) -> List[dict]: ...


class TableReader(Protocol):
    """Reads one table image, a single row, or answers a small structured question about an image."""
    def read_table(self, png: bytes, label: str = "table") -> List[Dict]: ...
    def read_row(self, png: bytes, label: str = "row") -> Optional[Dict]: ...
    def ask_json(self, png: bytes, prompt: str, label: str = "") -> Any: ...


class PageTableExtractor(Protocol):
    """Reads every table on one page of a PDF into rows of cells (OcrTable), whichever way it does it."""
    def extract(self, pdf: bytes, page: int, rotate: Any = "auto") -> List[Any]: ...


class TableLocator(Protocol):
    """Finds table frames on a page. Returns objects with page, x0, y0, x1, y1, rows, cols, xs, ys."""
    def find(self, pdf: bytes, page: int) -> Sequence[Any]: ...


class PageRenderer(Protocol):
    def page_count(self, pdf: bytes) -> int: ...
    def page_is_portrait(self, pdf: bytes, page: int) -> bool: ...
    def render_tiles(self, pdf: bytes, page: int, rotate: int = 0, cols: int = 1, rows: int = 1): ...
    def render_fraction(self, pdf: bytes, page: int, frac: Tuple[float, float, float, float], rotate: int = 0) -> bytes: ...
    def render_box(self, pdf: bytes, page: int, box, rotate: int = 0, dpi: int = 400) -> bytes: ...


class JobRepository(Protocol):
    def save(self, job: ExtractionJob) -> None: ...
    def get(self, job_id: str) -> Optional[ExtractionJob]: ...
    def list(self) -> List[ExtractionJob]: ...


class FileStorage(Protocol):
    def path(self, name: str) -> Path: ...
    def save(self, name: str, data: bytes) -> Path: ...
    def exists(self, name: str) -> bool: ...


class RunRecorder(Protocol):
    """Per-run log: steps, LLM calls, outputs."""
    def start(self, run_id: str, *, filename: str, stored_as: str, data: bytes, pages: int, owner_id: str = "") -> None: ...
    def begin(self, run_id: str, options: Dict) -> None: ...
    def step(self, run_id: str, name: str, **detail) -> ContextManager[Dict]: ...
    def finish(self, run_id: str, *, status: str, error: Optional[str], rows: int, issues: int) -> Optional[Dict]: ...
    def update_counts(self, run_id: str, *, rows: int, issues: int) -> None: ...
    def add_output(self, run_id: str, output: Dict) -> None: ...
    def record_call(self, call: Any) -> None: ...


class TemplateExporter(Protocol):
    """Writes rows into a customer's workbook template."""
    def __call__(self, template: Path, rows: List[dict], out: Path, sheets: Sequence[str], paint_factor: float = 1) -> Any: ...
